export interface SplitArguments {
  readonly input: JsonObject
  readonly idempotencyKey: string | null
}

/**
 * The idempotency key is the transport's business, not the domain's, so it is
 * taken out before the arguments are validated. Leaving it in would make every
 * use case schema reject it as an unknown property.
 */
export function splitArguments(raw: unknown): SplitArguments {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    return { input: {}, idempotencyKey: null }
  }

  const { [IDEMPOTENCY_KEY]: key, ...input } = raw as Record<string, JsonValue>
  return {
    input: input,
    idempotencyKey: typeof key === 'string' && key.trim() !== '' ? key : null,
  }
}
